const languageCodes = ["de", "en", "ru", "uk"];
const languageSelector = document.querySelector("#language-selector");
const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector("#primary-navigation");
const currentYear = document.querySelector("#current-year");
const description = document.querySelector('meta[name="description"]');

function translate(language) {
  const languageIndex = languageCodes.indexOf(language);

  if (languageIndex === -1) {
    return;
  }

  document.documentElement.lang = language;
  document.title = translations.pageTitle[languageIndex];
  if (description) {
    description.content = translations.pageDescription[languageIndex];
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translations[key][languageIndex];
  });

  document.querySelectorAll("[data-i18n-content]").forEach((element) => {
    const key = element.dataset.i18nContent;
    element.setAttribute("content", translations[key][languageIndex]);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    element.setAttribute("aria-label", translations[key][languageIndex]);
  });

  if (menuToggle) {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.querySelector(".sr-only").textContent =
      translations[isOpen ? "menuClose" : "menuOpen"][languageIndex];
  }
}

if (languageSelector) {
  languageSelector.addEventListener("change", (event) => {
    translate(event.target.value);
  });
}

if (menuToggle && navigation) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute("aria-expanded", String(!isOpen));
    menuToggle.querySelector(".sr-only").textContent = translations[isOpen ? "menuOpen" : "menuClose"][
      languageCodes.indexOf(document.documentElement.lang)
    ];
    navigation.classList.toggle("is-open", !isOpen);
  });

  navigation.addEventListener("click", (event) => {
    if (event.target instanceof Element && event.target.closest("a")) {
      menuToggle.setAttribute("aria-expanded", "false");
      menuToggle.querySelector(".sr-only").textContent =
        translations.menuOpen[languageCodes.indexOf(document.documentElement.lang)];
      navigation.classList.remove("is-open");
    }
  });
}

if (currentYear) {
  currentYear.textContent = String(new Date().getFullYear());
}

if (languageSelector) {
  translate(languageSelector.value);
}
